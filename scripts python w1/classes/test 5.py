n1 = int(input('enter a number:'))
n2 = int(input('enter another number:'))
a = n1 + n2
s = n1 - n2
m = n1 * n2
d = n1 / n2
dd = n1 // n2
e = n1 ** n2
print('the sum is: {}, the subtraction is: {} and the multiplication is: {}' .format(a, s, m))
print('the division is: {:.2f}, the integer division is: {} and the exponentiation is: {}' .format(d, dd, e))
input('press enter to exit')
